"""Test the real Sampark Samsung Chat -> local BART Description pipeline.

Uses the text that pdfplumber has already extracted. This is a local
diagnostic; it does not change Sampark data or upload files.

Copy this file to:
    C:\\scrappyV3\\scripts\\try_sampark_summary_on_extracted_text.py

From C:\\scrappyV3, use the EXISTING NewsScrapper Python environment:
    & ".\\venv\\Scripts\\python.exe" -u ".\\scripts\\try_sampark_summary_on_extracted_text.py"

Optional custom input:
    & ".\\venv\\Scripts\\python.exe" -u ".\\scripts\\try_sampark_summary_on_extracted_text.py" "C:\\path\\document_extracted.txt"

Do NOT use .docling-venv here; it may lack the BART weights/dependencies.
"""
from __future__ import annotations

import logging
import sys
from pathlib import Path


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    sys.path.insert(0, str(root))
    file = (
        Path(sys.argv[1]).expanduser().resolve()
        if len(sys.argv) > 1
        else root / "NewsScrapper_Real_Architecture_Atlas_extracted.txt"
    )
    if not file.is_file():
        print("ERROR: Extracted text file not found:", file, flush=True)
        print("Run extract_pdf_v2.py first, or provide the full .txt path.", flush=True)
        return 2

    summary_module = root / "news_scrapper" / "internal_content" / "document_summarizer.py"
    if not summary_module.is_file():
        print("ERROR: Missing:", summary_module, flush=True)
        print("Copy the Samsung Chat/BART version from the GitHub test branch.", flush=True)
        return 2

    logging.basicConfig(level=logging.WARNING, format="%(levelname)s: %(message)s")
    from news_scrapper.internal_content.document_summarizer import (
        DocumentSummaryUnavailable,
        document_evidence,
        summarize_document,
    )
    from news_scrapper.adapters import samsung_chat as chat

    content = file.read_text(encoding="utf-8")
    evidence = document_evidence(content)
    print("Input:", file, flush=True)
    print("Extracted characters:", f"{len(content):,}", flush=True)
    print("Evidence sections:", len(evidence), flush=True)
    print("Samsung Chat configured:", bool(all((chat.URL, chat.CLIENT, chat.TOKEN, chat.MODEL_ID))), flush=True)
    print("Engine order: Samsung Chat -> local BART", flush=True)
    print("Generating 300-character Description...", flush=True)

    try:
        summary, method = summarize_document(content, 300)
    except DocumentSummaryUnavailable as error:
        print("SUMMARY NOT AVAILABLE:", error, flush=True)
        print("Check Samsung Chat settings and the local DistilBART model installation.", flush=True)
        return 1

    print("\n" + "=" * 65, flush=True)
    print("SUMMARY ENGINE:", method, flush=True)
    print("DESCRIPTION (" + str(len(summary)) + " / 300 characters):", flush=True)
    print(summary, flush=True)
    print("=" * 65, flush=True)
    if not summary or len(summary) > 300 or method not in {"samsung_chat", "bart"}:
        print("ERROR: Unexpected summary result.", flush=True)
        return 1
    print("PASS: Summary generated by the configured model pipeline.", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
